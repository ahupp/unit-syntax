"""Regenerate the finite dimensional algebra and conservative symbolic fallbacks."""

from pathlib import Path
import importlib.util

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "_unit_dimensions", ROOT / "unit_syntax/typing.py"
)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
dims = module.DIMENSIONS
by_key = {module.dimension_key(d): name for name, d in dims.items()}


def combine(left, right, sign):
    result = left.copy()
    for key, power in right.items():
        result[key] = result.get(key, 0) + sign * power
    return by_key.get(module.dimension_key(result))


lines = [
    "# Generated by scripts/generate_typing.py; do not edit by hand.",
    "from collections.abc import Mapping, Sequence",
    "from typing import Any, Generic, Literal as Literal, TypeVar, overload",
    "",
    'K = TypeVar("K")',
    'D = TypeVar("D")',
    'E = TypeVar("E")',
    "",
    "class Dimension(Generic[K]): ...",
    "class Product(Generic[D, E]): ...",
    "class Quotient(Generic[D, E]): ...",
    "class PowerOf(Generic[D, E]): ...",
    "",
]
for name, dimensions in dims.items():
    lines.append(f"{name} = Dimension[Literal[{module.dimension_key(dimensions)!r}]]")
lines += [
    "",
    "DIMENSIONS: dict[str, dict[str, int]]",
    "def dimension_key(dimensions: Mapping[str, float]) -> str: ...",
    "",
    "class Quantity(Generic[D]):",
    "    def __init__(self, value: float | complex | Sequence[float] | Quantity[D], units: str) -> None: ...",
    "    magnitude: Any",
    "    units: Any",
    "    def __float__(self: Quantity[Dimensionless]) -> float: ...",
    "    def to(self, units: str) -> Quantity[D]: ...",
    "    def to_base_units(self) -> Quantity[D]: ...",
    "    def to_reduced_units(self) -> Quantity[D]: ...",
    "    def __neg__(self) -> Quantity[D]: ...",
    "    def __pos__(self) -> Quantity[D]: ...",
    "    def __abs__(self) -> Quantity[D]: ...",
    "    def __getitem__(self, index: Any) -> Quantity[D]: ...",
]


def overload(name, parameters, result, self_type=""):
    lines.extend(
        [
            "    @overload",
            f'    def {name}(self{": " + self_type if self_type else ""}, {parameters}) -> {result}: ...',
        ]
    )


for operator in [
    "__add__",
    "__sub__",
    "__mod__",
    "__lt__",
    "__le__",
    "__gt__",
    "__ge__",
]:
    result = (
        "bool"
        if operator in ["__lt__", "__le__", "__gt__", "__ge__"]
        else "Quantity[D]"
    )
    overload(operator, "other: Quantity[D]", result)
    overload(
        operator,
        "other: float",
        "bool" if result == "bool" else "Quantity[Dimensionless]",
        "Quantity[Dimensionless]",
    )
for operator in ["__radd__", "__rsub__"]:
    lines.append(
        f"    def {operator}(self: Quantity[Dimensionless], other: float) -> Quantity[Dimensionless]: ..."
    )

for operator, sign in [("__mul__", 1), ("__truediv__", -1)]:
    # Put the generic identities first; they preserve arbitrary dimensions.
    if sign == -1:
        overload(operator, "other: Quantity[D]", "Quantity[Dimensionless]")
    overload(operator, "other: float | Quantity[Dimensionless]", "Quantity[D]")
    if sign == 1:
        overload(
            operator, "other: Quantity[E]", "Quantity[E]", "Quantity[Dimensionless]"
        )
    for left, a in dims.items():
        for right, b in dims.items():
            if (
                right == "Dimensionless"
                or left == right
                and sign == -1
                or left == "Dimensionless"
                and sign == 1
            ):
                continue
            result = combine(a, b, sign)
            if result:
                overload(
                    operator,
                    f"other: Quantity[{right}]",
                    f"Quantity[{result}]",
                    f"Quantity[{left}]",
                )
    symbolic = "Product" if sign == 1 else "Quotient"
    overload(operator, "other: Quantity[E]", f"Quantity[{symbolic}[D, E]]")
lines.append("    def __rmul__(self, other: float) -> Quantity[D]: ...")
for name, dimensions in dims.items():
    result = combine({}, dimensions, -1)
    if result:
        overload(
            "__rtruediv__", "other: float", f"Quantity[{result}]", f"Quantity[{name}]"
        )
overload("__rtruediv__", "other: float", "Quantity[Quotient[Dimensionless, D]]")
overload(
    "__pow__", "exponent: float", "Quantity[Dimensionless]", "Quantity[Dimensionless]"
)
for power in [-3, -2, -1, 0, 1, 2, 3, 4]:
    for name, dimensions in dims.items():
        if name == "Dimensionless":
            continue
        result = by_key.get(
            module.dimension_key(
                {key: value * power for key, value in dimensions.items()}
            )
        )
        if result:
            overload(
                "__pow__",
                f"exponent: Literal[{power}]",
                f"Quantity[{result}]",
                f"Quantity[{name}]",
            )
    result = (
        "Dimensionless"
        if power == 0
        else "D" if power == 1 else f"PowerOf[D, Literal[{power}]]"
    )
    overload("__pow__", f"exponent: Literal[{power}]", f"Quantity[{result}]")
lines.append("")
(ROOT / "unit_syntax/typing.pyi").write_text("\n".join(lines))
